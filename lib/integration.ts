// Shell integration for the plugin's own "Run blocks" terminals.
//
// The plugin never adds text to the commands it runs. Instead, its terminals
// start the user's zsh or bash with a small startup wrapper that loads the
// user's own startup files first and then adds prompt hooks that print the
// standard OSC 133 marks (C before a command's output, D;<exit code> after it,
// A and B around the prompt). This is the same scheme VS Code, iTerm2 and
// Warp use.
//
// This module is pure: it builds the file contents and the terminal argv.
// `integration-files.ts` writes the files on the server.

export type ShellKind = "zsh" | "bash";

/** File names inside the integration directory. */
export const ZSH_DIR = "zsh";
export const ZSH_FILES = [".zshenv", ".zprofile", ".zshrc", ".zlogin"] as const;
export const BASH_RCFILE = "bash/runnable-blocks.bashrc";
/** Bumped when the generated files change, so old copies are rewritten. */
export const INTEGRATION_VERSION = 1;

/** zsh or bash from a shell path (`/bin/zsh`, `/opt/homebrew/bin/bash`, `-zsh`), else null. */
export function shellKind(shellPath: string): ShellKind | null {
  const base = shellPath.split("/").pop() ?? "";
  const name = base.replace(/^-/, "").replace(/(-|)\d+(\.\d+)*$/, "");
  if (name === "zsh") return "zsh";
  if (name === "bash") return "bash";
  return null;
}

/** POSIX single-quote quoting: safe for any string, including spaces and quotes. */
export function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

const HEADER = (shell: string) =>
  `# Runnable Blocks shell integration for ${shell} (v${INTEGRATION_VERSION}).\n` +
  "# Generated by the bb plugin \"runnable-blocks\"; it is rewritten on every load.\n" +
  "# Loads your own startup files, then adds OSC 133 prompt marks so the plugin\n" +
  "# can show each command's exit status. It never changes your commands.\n";

/**
 * zsh: one stage of the ZDOTDIR wrapper. zsh reads every startup file from
 * $ZDOTDIR, so the plugin's terminal starts zsh with ZDOTDIR pointing here.
 * Each stage puts the user's own ZDOTDIR back while their file runs (their
 * file may read or change it), then points zsh at the wrapper again for the
 * next stage. The .zshrc stage leaves the user's value in place for good.
 *
 * Shell variables used (all prefixed __bb_rb_):
 *   __bb_rb_wrap_zd  this wrapper directory
 *   __bb_rb_user_zd  the user's startup directory ($ZDOTDIR or $HOME)
 *   __bb_rb_zd_set   non-empty when the user has a ZDOTDIR at all
 */
function zshStage(file: string, final: boolean): string {
  return [
    `if [[ -n \${__bb_rb_zd_set-} ]]; then ZDOTDIR=\$__bb_rb_user_zd; else unset ZDOTDIR; fi`,
    `[[ -r "\$__bb_rb_user_zd/${file}" ]] && builtin source "\$__bb_rb_user_zd/${file}"`,
    // Their file may have set or moved ZDOTDIR; later files come from there.
    `if [[ -n \${ZDOTDIR+x} ]]; then __bb_rb_user_zd=\$ZDOTDIR; __bb_rb_zd_set=1; fi`,
    final
      ? `if [[ -n \${__bb_rb_zd_set-} ]]; then export ZDOTDIR=\$__bb_rb_user_zd; else unset ZDOTDIR; fi`
      : `ZDOTDIR=\$__bb_rb_wrap_zd`,
    "",
  ].join("\n");
}

/** The prompt hooks, installed after the user's .zshrc. Safe to source twice. */
export const ZSH_HOOKS = `if [[ -z \${__bb_rb_hooked-} ]]; then
  typeset -g __bb_rb_hooked=1 __bb_rb_ran=
  __bb_rb_preexec() {
    __bb_rb_ran=1
    builtin printf '\\033]133;C\\007'
  }
  __bb_rb_precmd() {
    local __bb_rb_status=$?
    if [[ -n $__bb_rb_ran ]]; then
      builtin printf '\\033]133;D;%s\\007' "$__bb_rb_status"
      __bb_rb_ran=
    fi
    builtin printf '\\033]133;A\\007'
    return $__bb_rb_status
  }
  __bb_rb_prompt_end() {
    local __bb_rb_status=$?
    # Mark the end of the prompt; %{ %} keeps it out of the prompt width.
    if [[ -o promptpercent && $PS1 != *$'\\e]133;B'* ]]; then
      PS1+=$'%{\\e]133;B\\a%}'
    fi
    return $__bb_rb_status
  }
  autoload -Uz add-zsh-hook
  # First, so $? is still the command's exit status; the user's hooks keep theirs.
  precmd_functions=(__bb_rb_precmd \${precmd_functions[@]:#__bb_rb_precmd})
  # Last, after themes that rebuild PS1 in their own precmd.
  add-zsh-hook precmd __bb_rb_prompt_end
  add-zsh-hook preexec __bb_rb_preexec
fi
`;

/** Contents of each wrapper file, keyed by file name. */
export function zshWrapperFiles(): Record<(typeof ZSH_FILES)[number], string> {
  const zshenv =
    HEADER("zsh") +
    // Runs first. The terminal's launcher passed the user's ZDOTDIR (if any)
    // in BB_RB_USER_ZDOTDIR(_SET); keep it in shell variables and drop the
    // environment copies so child processes never see them.
    `typeset -g __bb_rb_wrap_zd=\${ZDOTDIR-}\n` +
    `if [[ -n \${BB_RB_USER_ZDOTDIR_SET-} ]]; then\n` +
    `  typeset -g __bb_rb_user_zd=\${BB_RB_USER_ZDOTDIR-} __bb_rb_zd_set=1\n` +
    `else\n` +
    `  typeset -g __bb_rb_user_zd=\${HOME} __bb_rb_zd_set=\n` +
    `fi\n` +
    `unset BB_RB_USER_ZDOTDIR BB_RB_USER_ZDOTDIR_SET\n` +
    zshStage(".zshenv", false);
  return {
    ".zshenv": zshenv,
    ".zprofile": HEADER("zsh") + zshStage(".zprofile", false),
    ".zshrc": HEADER("zsh") + zshStage(".zshrc", true) + ZSH_HOOKS,
    // Normally unused: .zshrc already handed ZDOTDIR back, so zsh reads the
    // user's own .zlogin. Kept for login shells that skip .zshrc.
    ".zlogin": HEADER("zsh") + zshStage(".zlogin", true),
  };
}

/** The bash --rcfile. Loads the user's files, then the hooks. Safe to source twice. */
export function bashRcfile(): string {
  return (
    HEADER("bash") +
    `if [ -z "\${__bb_rb_loaded-}" ]; then
__bb_rb_loaded=1
if shopt -q login_shell; then
  [ -r /etc/profile ] && . /etc/profile
  if [ -r "$HOME/.bash_profile" ]; then . "$HOME/.bash_profile"
  elif [ -r "$HOME/.bash_login" ]; then . "$HOME/.bash_login"
  elif [ -r "$HOME/.profile" ]; then . "$HOME/.profile"
  fi
else
  # --rcfile replaces ~/.bashrc; load it (and the system one, when present).
  [ -r /etc/bash.bashrc ] && . /etc/bash.bashrc
  [ -r "$HOME/.bashrc" ] && . "$HOME/.bashrc"
fi
fi
if [ -z "\${__bb_rb_hooked-}" ]; then
__bb_rb_hooked=1
__bb_rb_first=1
__bb_rb_at_prompt=
__bb_rb_prompt_start() {
  local __bb_rb_status=$?
  if [ -z "$__bb_rb_first" ]; then
    builtin printf '\\033]133;D;%s\\007' "$__bb_rb_status"
  fi
  __bb_rb_first=
  builtin printf '\\033]133;A\\007'
  return $__bb_rb_status
}
__bb_rb_prompt_end() {
  local __bb_rb_status=$?
  case "$PS1" in
    *$'\\e]133;B'*) ;;
    *) PS1="$PS1"$'\\[\\e]133;B\\a\\]' ;;
  esac
  __bb_rb_at_prompt=1
  return $__bb_rb_status
}
# PROMPT_COMMAND: ours first (so $? is the command's), the user's, then the prompt-end mark.
if [[ "$(declare -p PROMPT_COMMAND 2>/dev/null)" == "declare -a"* ]]; then
  PROMPT_COMMAND=(__bb_rb_prompt_start "\${PROMPT_COMMAND[@]}" __bb_rb_prompt_end)
elif [ -n "\${PROMPT_COMMAND-}" ]; then
  PROMPT_COMMAND="__bb_rb_prompt_start"$'\\n'"$PROMPT_COMMAND"$'\\n'"__bb_rb_prompt_end"
else
  PROMPT_COMMAND="__bb_rb_prompt_start"$'\\n'"__bb_rb_prompt_end"
fi
if [ "\${BASH_VERSINFO[0]}" -gt 4 ] || { [ "\${BASH_VERSINFO[0]}" -eq 4 ] && [ "\${BASH_VERSINFO[1]}" -ge 4 ]; }; then
  # bash 4.4+: PS0 prints after a line is read, before it runs.
  PS0="\${PS0-}"$'\\e]133;C\\a'
elif [ -z "$(trap -p DEBUG)" ]; then
  # Older bash: the first DEBUG trap after the prompt marks the start (only
  # when the user has no DEBUG trap of their own).
  __bb_rb_debug() {
    if [ -n "$__bb_rb_at_prompt" ]; then
      __bb_rb_at_prompt=
      builtin printf '\\033]133;C\\007'
    fi
  }
  trap '__bb_rb_debug' DEBUG
fi
fi
`
  );
}

export interface IntegrationPaths {
  /** The zsh ZDOTDIR wrapper directory. */
  zshDir: string;
  /** The bash --rcfile. */
  bashRcfile: string;
}

/**
 * Launcher for zsh. bb runs argv through the user's shell (`$SHELL -lc`), so
 * this reads ZDOTDIR from the terminal's real environment at start time,
 * hands it to the wrapper, and points zsh at the wrapper. Paths arrive as
 * positional arguments, never spliced into the script.
 */
export const ZSH_LAUNCHER =
  'if [ "${ZDOTDIR+set}" = set ]; then BB_RB_USER_ZDOTDIR=$ZDOTDIR; BB_RB_USER_ZDOTDIR_SET=1; ' +
  "else BB_RB_USER_ZDOTDIR=; BB_RB_USER_ZDOTDIR_SET=; fi; " +
  'export BB_RB_USER_ZDOTDIR BB_RB_USER_ZDOTDIR_SET; ZDOTDIR=$1; export ZDOTDIR; exec "$2" -i';

/** The `terminals.create` argv for an integrated shell. */
export function integratedArgv(kind: ShellKind, shellPath: string, paths: IntegrationPaths): string[] {
  if (kind === "zsh") return ["/bin/sh", "-c", ZSH_LAUNCHER, "runnable-blocks", paths.zshDir, shellPath];
  return [shellPath, "--rcfile", paths.bashRcfile, "-i"];
}
